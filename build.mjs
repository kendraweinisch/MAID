// Builds the static site into dist/. No dependencies: run `node build.mjs`.
import { mkdir, readFile, writeFile, rm, cp } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { layout, site } from './src/layout.mjs';
import { home, guides, checklists, maidHub, placePage, maidPages, staticPages, notFound } from './src/pages.mjs';
import { printables, printablesIndex, binderPage } from './src/printables.mjs';
import { buildSearchIndex } from './src/search-index.mjs';
import { journeys } from './src/journeys.mjs';
import { adPages } from './src/advance-directives.mjs';
import { esPages } from './src/es.mjs';
import { esMaidPages } from './src/es-maid.mjs';
import { esBatch2 } from './src/es-batch2.mjs';
import { esBatch3a } from './src/es-batch3a.mjs';
import { esBatch3b } from './src/es-batch3b.mjs';
import { esPrintPages, ES_PRINTABLES, ES_BINDER } from './src/es-print.mjs';
import { esStaticPages } from './src/es-static.mjs';
import { appPages } from './src/app-pages.mjs';
import { costPages } from './src/cost-database.mjs';

const out = 'dist';
// BASE_PATH serves the site from a sub-folder, e.g. "/maid" on username.github.io/maid/.
// Leave it empty once the site is on its own domain.
const base = (process.env.BASE_PATH || '').replace(/\/$/, '');
const withBase = (html) =>
  base
    ? html
        .replace(/<html lang="(en|es)">/, `<html lang="$1" data-base="${base}">`)
        .replace(/(href|action|src)="\/(?!\/)/g, `$1="${base}/`)
    : html;
const data = JSON.parse(await readFile('src/data/places.json', 'utf8'));

const pages = [
  home(data),
  ...journeys,
  ...guides,
  ...adPages,
  ...costPages,
  printablesIndex({ planAhead: checklists[0], doctor: checklists[1], afterDeath: checklists[2] }),
  ...checklists,
  ...printables,
  binderPage(),
  maidHub(data),
  ...maidPages,
  ...data.places.map(placePage),
  ...staticPages,
  ...esPages,
  ...esMaidPages,
  ...esBatch2,
  ...esBatch3a,
  ...esBatch3b,
  ...esPrintPages,
  ...esStaticPages,
  ...appPages,
];

await rm(out, { recursive: true, force: true });
for (const page of [...pages, notFound]) {
  const file = page.path.endsWith('.html') ? join(out, page.path) : join(out, page.path, 'index.html');
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, withBase(layout(page)));
}

await cp('src/styles.css', join(out, 'styles.css'));

// Knowledge base for the Ask assistant: the site's own text, by section.
const isEs = (p) => p.path.startsWith('/es/');
await writeFile(join(out, 'search-index.json'), JSON.stringify(buildSearchIndex(pages.filter((p) => !isEs(p)), (p) => p.body)));
await writeFile(join(out, 'search-index-es.json'), JSON.stringify(buildSearchIndex(pages.filter(isEs), (p) => p.body)));
await cp('public', out, { recursive: true });
// Lists for the PDF scripts: Spanish printables, and the Spanish binder's order.
await writeFile(join(out, 'es-printables.json'), JSON.stringify(ES_PRINTABLES.map(({ slug, path }) => ({ slug, path }))));
await writeFile(join(out, 'es-binder.json'), JSON.stringify(ES_BINDER.flatMap(([, l]) => l.map(([slug]) => slug))));

const urls = pages.filter((p) => !['/thanks/', '/offline/', '/es/sin-conexion/'].includes(p.path)).map((p) => `<url><loc>${site.url}${p.path}</loc></url>`).join('\n');
await writeFile(join(out, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`);

// Offline support: a service worker that saves the key pages on first visit
// and keeps every page a visitor opens. A new version on every build, so
// phones pick up updates.
const PRECACHE = [
  '/', '/offline/', '/app/', '/styles.css', '/app.js', '/journey.js', '/assistant.js', '/search-index.json', '/favicon.svg', '/icon-192.png', '/images/atlas-map.svg',
  '/for-myself/', '/for-someone-i-love/', '/plan-ahead/', '/serious-illness/hospice-vs-palliative-care/', '/last-weeks/', '/last-weeks/signs-death-is-near/',
  '/after-a-death/', '/checklists/after-a-death/', '/grief/', '/checklists/', '/printables/after-a-death.pdf',
  '/es/', '/es/sin-conexion/', '/es/app/', '/search-index-es.json', '/es/para-mi/', '/es/para-un-ser-querido/', '/es/planificar/', '/es/cuidados-paliativos-y-hospicio/',
  '/es/ultimas-semanas/', '/es/senales-de-que-la-muerte-esta-cerca/', '/es/despues-de-una-muerte/', '/es/primeras-24-horas/', '/es/duelo/', '/es/imprimibles/', '/printables/primeras-24-horas.pdf',
];
const swVersion = new Date().toISOString();
const sw = `/* Generated by build.mjs. End of Life Atlas offline support. */
const BASE = ${JSON.stringify(base)};
const VERSION = ${JSON.stringify(swVersion)};
const CORE = 'atlas-core-' + VERSION;
const PAGES = 'atlas-pages';
const ASSETS = 'atlas-assets-' + VERSION;
const PRECACHE = ${JSON.stringify(PRECACHE)}.map((p) => BASE + p);

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CORE).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CORE && k !== PAGES && k !== ASSETS && !k.startsWith('atlas-fonts')).map((k) => caches.delete(k)))).then(() => self.clients.claim())
  );
});

const offlinePage = (url) => (new URL(url).pathname.startsWith(BASE + '/es/') ? BASE + '/es/sin-conexion/' : BASE + '/offline/');

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Fonts: keep a copy once loaded.
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith(caches.open('atlas-fonts').then((c) => c.match(req).then((hit) => hit || fetch(req).then((res) => { c.put(req, res.clone()); return res; }))));
    return;
  }
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE + '/')) return;
  // Pages: the newest version when online, the saved copy when not.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => { if (res.ok) { const copy = res.clone(); caches.open(PAGES).then((c) => c.put(req, copy)); } return res; })
        .catch(() => caches.match(req, { ignoreSearch: true }).then((hit) => hit || caches.match(offlinePage(req.url))))
    );
    return;
  }
  // Everything else: serve the saved copy at once, refresh it in the background.
  event.respondWith(
    caches.match(req).then((hit) => {
      const fresh = fetch(req).then((res) => { if (res.ok) { const copy = res.clone(); caches.open(ASSETS).then((c) => c.put(req, copy)); } return res; }).catch(() => hit);
      return hit || fresh;
    })
  );
});
`;
await writeFile(join(out, 'sw.js'), sw);

const indexable = process.env.SITE_INDEXABLE === 'true';
await writeFile(join(out, 'robots.txt'), indexable ? `User-agent: *\nAllow: /\nSitemap: ${site.url}/sitemap.xml\n` : 'User-agent: *\nDisallow: /\n');

console.log(`Built ${pages.length + 1} pages into ${out}/ (base path "${base || '/'}", search indexing ${indexable ? 'on' : 'off'})`);
